"""Storage for driver's license uploads.

Files are encrypted before they touch the disk and are never served from a
public URL — only the admin API can read them back. Local disk for now;
swap the three functions for Cloudflare R2 (S3 API) at deployment.
"""
from __future__ import annotations

import os
import secrets

from flask import current_app
from werkzeug.datastructures import FileStorage

from .. import crypto
from ..errors import ApiError

ALLOWED = {
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
    ".heic": "image/heic",
    ".pdf": "application/pdf",
}


def _path(key: str) -> str:
    # Keys are generated by us (hex + known extension); refuse anything else.
    if "/" in key or "\\" in key or key.startswith("."):
        raise ValueError("invalid storage key")
    return os.path.join(current_app.config["UPLOAD_DIR"], key + ".enc")


def save_license(file: FileStorage | None) -> str:
    if file is None or not file.filename:
        raise ApiError("Please upload a photo of your driver's license.")
    ext = os.path.splitext(file.filename)[1].lower()
    if ext not in ALLOWED:
        raise ApiError("License must be a JPG, PNG, WEBP, HEIC or PDF file.")
    data = file.read()
    if not data:
        raise ApiError("The uploaded license file is empty.")
    key = secrets.token_hex(16) + ext
    os.makedirs(current_app.config["UPLOAD_DIR"], exist_ok=True)
    with open(_path(key), "wb") as fh:
        fh.write(crypto.encrypt_bytes(data))
    return key


def read_license(key: str) -> tuple[bytes, str]:
    with open(_path(key), "rb") as fh:
        data = crypto.decrypt_bytes(fh.read())
    ext = os.path.splitext(key)[1].lower()
    return data, ALLOWED.get(ext, "application/octet-stream")


def delete_license(key: str | None) -> None:
    if not key:
        return
    try:
        os.remove(_path(key))
    except FileNotFoundError:
        pass
